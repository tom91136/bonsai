package net.kurobako.bonsai.plugin

/** The checks of the compiler plugin, named by the ids its options and messages use; `strict` checks are errors in the
  * ci mode.
  */
private enum Check(val id: String, val strict: Boolean = false, val severity: Severity = Severity.Warning) {
  case Acyclic                 extends Check("acyclic", strict = true)
  case ArrayEquality           extends Check("array-equality", strict = true)
  case IteratorEquality        extends Check("iterator-equality", strict = true)
  case UnorderedComparison     extends Check("unordered-comparison", strict = true)
  case LongArguments           extends Check("long-arguments", strict = true)
  case SameTypeArguments       extends Check("same-type-arguments", strict = true)
  case SwappedArguments        extends Check("swapped-arguments", strict = true)
  case BooleanArgument         extends Check("boolean-argument", strict = true)
  case OpenTypeTest            extends Check("open-type-test")
  case ExtractorTypeTest       extends Check("extractor-type-test", strict = true)
  case NamedPattern            extends Check("named-pattern", strict = true)
  case UnitMap                 extends Check("unit-map", strict = true)
  case RedundantConversion     extends Check("redundant-conversion", strict = true)
  case NestedFuture            extends Check("nested-future", strict = true)
  case LinearInLoop            extends Check("linear-in-loop", strict = true)
  case LoopBoxing              extends Check("loop-boxing")
  case StrictChain             extends Check("strict-chain")
  case LocalThrow              extends Check("local-throw", strict = true)
  case ThrowInDefault          extends Check("throw-in-default", strict = true)
  case ThrowingHelper          extends Check("throwing-helper", strict = true)
  case PartialInTry            extends Check("partial-in-try", strict = true)
  case RedundantTry            extends Check("redundant-try", strict = true)
  case BroadCatch              extends Check("broad-catch", strict = true)
  case DiscardedCause          extends Check("discarded-cause", strict = true)
  case EagerEffect             extends Check("eager-effect")
  case IdentityToken           extends Check("identity-token")
  case BlockingCommonPool      extends Check("blocking-common-pool")
  case UnguardedClose          extends Check("unguarded-close")
  case OrphanThread            extends Check("orphan-thread")
  case ReimplementedJoin       extends Check("reimplemented-join")
  case UnboundedWait           extends Check("unbounded-wait")
  case MessageClassification   extends Check("message-classification")
  case WriteOnlyField          extends Check("write-only-field")
  case RegexInDef              extends Check("regex-in-def")
  case UnspecialisedFunction   extends Check("unspecialised-function")
  case AccumulatingConcat      extends Check("accumulating-concat")
  case TupleDestructure        extends Check("tuple-destructure-in-loop")
  case InvariantInLoop         extends Check("invariant-in-loop")
  case KeyedLookupInLoop       extends Check("keyed-lookup-in-loop")
  case BoxingFold              extends Check("boxing-fold")
  case InlineSetMembership     extends Check("inline-set-membership")
  case LiteralTableInDef       extends Check("literal-table-in-def")
  case InlineFunctionParameter extends Check("inline-function-parameter")
  case InlineParameterReuse    extends Check("inline-parameter-reuse")
  case InlineInstanceParameter extends Check("inline-instance-parameter")
  case ShadowedExtension       extends Check("shadowed-extension", strict = true)
  case AccidentalSelfCall      extends Check("accidental-self-call", severity = Severity.Error)
  case CheckedOverloadBypass   extends Check("checked-overload-bypass", severity = Severity.Info)
  case BoxedOpaqueEquality     extends Check("boxed-opaque-equality")
  case InferredRefinedType     extends Check("inferred-refined-type", severity = Severity.Info)
  case UnrelatedTypeTest       extends Check("unrelated-type-test", severity = Severity.Error)
  case NowarnSuppression       extends Check("nowarn-suppression")
  case WrappedConversion       extends Check("wrapped-conversion", strict = true)
  case LambdaTrait             extends Check("lambda-trait")
  case FunctionAppliedOnce     extends Check("function-applied-once")
  case ForwardingAlias         extends Check("forwarding-alias")
  case UnusedPrivateParam      extends Check("unused-private-param")
  case ParameterObjectUnpacked extends Check("parameter-object-unpacked")
  case JdkInternal             extends Check("jdk-internal")
}
