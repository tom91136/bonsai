package net.kurobako.bonsai.analysis

import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.PathMatcher
import scala.jdk.CollectionConverters.*
import scala.util.Using

/** The files in the outputs of a build, and what they name. */
private[analysis] object Outputs {

  private val Header = "// Generated by the Scala Plugin for the Protocol Buffer Compiler."

  // possessive, as a backtracking loop recurses per comment and overflows on a commented-out file
  private val LeadingComments = """(?s)(?:\s+|//[^\n]*|/\*.*?\*/)*+""".r

  private val GeneratedTag = """(?<!\w)@generated(?!\w)""".r

  def isGenerated(generated: Vector[PathMatcher], path: String): Boolean =
    generated.exists(_.matches(Path.of(path)))

  def generated(file: Path): Boolean =
    Files.isRegularFile(file) && marked(String(Files.readAllBytes(file), StandardCharsets.UTF_8))

  def marked(text: String): Boolean = {
    val leading = LeadingComments.findPrefixOf(text).getOrElse("")
    leading.linesIterator.exists(_.trim == Header) || GeneratedTag.findFirstIn(leading).isDefined
  }

  /** The regular files under `directory` in path order, as the file system's own order depends on how it was written.
    */
  def files(directory: Path): Vector[Path] =
    if (!Files.isDirectory(directory)) Vector.empty
    else Using.resource(Files.walk(directory))(_.toList.asScala.toVector.filter(Files.isRegularFile(_)).sorted)

  // Classes instantiated reflectively by ServiceLoader, the compiler plugin loader or sbt plugin discovery.
  def entryPoints(directory: Path): Vector[Root] = {
    val services = files(directory.resolve("META-INF/services")).view.flatMap(Files.readAllLines(_).asScala)
      .map(_.takeWhile(_ != '#').trim).toVector
    def lines(file: Path) = Some(file).filter(Files.isRegularFile(_)).toVector.flatMap(Files.readAllLines(_).asScala)
    val plugins           = lines(directory.resolve("plugin.properties")).collect {
      case line if line.startsWith("pluginClass=") => line.stripPrefix("pluginClass=").trim
    }
    val autoplugins = lines(directory.resolve("sbt/sbt.autoplugins")).map(_.trim)
    (services ++ plugins ++ autoplugins).view.collect {
      case name if name.nonEmpty => Root(name.stripSuffix("$").replace('$', '.'), Root.Kind.Provided)
    }.toVector
  }
}
