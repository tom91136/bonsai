package net.kurobako.bonsai.analysis

class GeneratedSuite extends AnalysisSuite {

  private val Header = "// Generated by the Scala Plugin for the Protocol Buffer Compiler."

  private val Annotations = Seq(
    "javax/annotation/Generated.java" -> (
      "package javax.annotation;\n\n@java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.SOURCE)\n" +
        "public @interface Generated { String[] value(); }\n"
    ),
    "jakarta/annotation/Generated.java" -> (
      "package jakarta.annotation;\n\n@java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.SOURCE)\n" +
        "public @interface Generated { String[] value(); }\n"
    ),
    "other/Generated.java" -> "package other;\n\npublic @interface Generated { String value(); }\n"
  )

  private def flagged(result: Extraction.Result, names: String*): Vector[String] =
    names.toVector.filter(result.graph.nodes(_).generated)

  test("the ScalaPB header marks a Scala source as generated") {
    val result = extract(
      Seq(
        "demo/Point.scala" ->
          s"$Header\n// DO NOT EDIT!\n// source: point.proto\n\npackage demo\n\nfinal case class Point(x: Int)\n"
      )
    )
    assertEquals(flagged(result, "demo.Point"), Vector("demo.Point"))
  }

  test("an @generated tag in the leading comments marks a Scala source as generated") {
    val result = extract(
      Seq(
        "demo/Block.scala" -> "/* @generated by the tool */\npackage demo\n\nfinal class Block\n",
        "demo/Line.scala"  -> "// @generated\npackage demo\n\nimport scala.util.Random\n\nfinal class Line\n"
      )
    )
    assertEquals(flagged(result, "demo.Block", "demo.Line"), Vector("demo.Block", "demo.Line"))
  }

  test("a javax.annotation.processing.Generated annotation marks a Scala type and the types nested in it") {
    val result = extract(
      Seq(
        "demo/Gen.scala" -> (
          "package demo\n\n" +
            "@javax.annotation.processing.Generated(value = Array(\"tool\"), date = \"\", comments = \"\")\n" +
            "final class Gen {\n  final class Inner\n}\n"
        )
      )
    )
    assertEquals(flagged(result, "demo.Gen", "demo.Gen.Inner"), Vector("demo.Gen", "demo.Gen.Inner"))
  }

  test("a mention, a late tag, a literal or a similar header leaves a Scala source hand-written") {
    val result = extract(
      Seq(
        "demo/Mention.scala" -> "// the parser is generated by hand\npackage demo\n\nfinal class Mention\n",
        "demo/Late.scala"    -> "package demo\n\n// @generated\nfinal class Late\n",
        "demo/Literal.scala" -> "package demo\n\nfinal class Literal { val tag = \"@generated\" }\n",
        "demo/Suffix.scala"  -> "// @generated_by tool\npackage demo\n\nfinal class Suffix\n",
        "demo/Lower.scala"   ->
          "// generated by the Scala Plugin for the Protocol Buffer Compiler.\npackage demo\n\nfinal class Lower\n",
        "demo/Grpc.scala" -> "// Generated by the Scala Plugin for gRPC.\npackage demo\n\nfinal class Grpc\n"
      )
    )
    assertEquals(
      flagged(result, "demo.Mention", "demo.Late", "demo.Literal", "demo.Suffix", "demo.Lower", "demo.Grpc"),
      Vector.empty[String]
    )
  }

  test("the ScalaPB header and an @generated tag mark a Java source as generated") {
    val result = javaFacts(
      Set.empty,
      "demo/Header.java" -> s"$Header\npackage demo;\n\npublic class Header {}\n",
      "demo/Tagged.java" -> "/** @generated */\npackage demo;\n\npublic class Tagged {}\n"
    )
    assertEquals(flagged(result, "demo.Header", "demo.Tagged"), Vector("demo.Header", "demo.Tagged"))
  }

  test("the javax, javax.processing and jakarta Generated annotations mark a Java type") {
    val result = javaFacts(
      Set.empty,
      (Annotations ++ Seq(
        "demo/Javax.java"      -> "package demo;\n\n@javax.annotation.Generated(\"tool\")\npublic class Javax {}\n",
        "demo/Processing.java" -> (
          "package demo;\n\n@javax.annotation.processing.Generated(\"tool\")\npublic class Processing {\n" +
            "  public int f() { return 1; }\n}\n"
        ),
        "demo/Jakarta.java" -> "package demo;\n\n@jakarta.annotation.Generated(\"tool\")\npublic class Jakarta {}\n"
      ))*
    )
    assertEquals(
      flagged(result, "demo.Javax", "demo.Processing", "demo.Jakarta"),
      Vector("demo.Javax", "demo.Processing", "demo.Jakarta")
    )
  }

  test("another package's Generated annotation, a late tag or a mention leaves a Java source hand-written") {
    val result = javaFacts(
      Set.empty,
      (Annotations ++ Seq(
        "demo/Imported.java" ->
          "package demo;\n\nimport other.Generated;\n\n@Generated(\"tool\")\npublic class Imported {}\n",
        "demo/Qualified.java" -> "package demo;\n\n@other.Generated(\"tool\")\npublic class Qualified {}\n",
        "demo/Mention.java"   -> "// the parser is generated by hand\npackage demo;\n\npublic class Mention {}\n",
        "demo/Late.java"      -> "package demo;\n\n// @generated\npublic class Late {}\n"
      ))*
    )
    assertEquals(
      flagged(result, "demo.Imported", "demo.Qualified", "demo.Mention", "demo.Late"),
      Vector.empty[String]
    )
  }
}
