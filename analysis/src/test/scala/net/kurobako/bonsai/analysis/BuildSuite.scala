package net.kurobako.bonsai.analysis

import java.nio.file.Files
import java.nio.file.Path
import munit.FunSuite
import net.kurobako.bonsai.testing.*

class BuildSuite extends FunSuite {
  private def withRoot(name: String)(body: Path => Unit): Unit =
    test(name)(Scratch.using("bonsai-build-")(body))

  private def write(root: Path, relative: String, content: String): Path = {
    val file = root.resolve(relative)
    Files.createDirectories(file.getParent)
    Files.writeString(file, content)
  }

  withRoot("an unknown scope is named whichever record gives it") { root =>
    Vector("output", "source", "model").foreach { tag =>
      val manifest = write(root, s"$tag.tsv", s"$tag\tcore\tclasses\t/x\n")
      assert(Manifest.read(manifest).left.exists(_.contains("unknown scope: classes")), tag)
    }
  }

  withRoot("the manifest carries compiler options and hand-written sources") { root =>
    val manifest = write(
      root,
      "manifest.tsv",
      s"option\tcore\t-Werror\noption\tcore\t-deprecation\nsource\tcore\tmain\t${root.resolve("A.scala")}\nroot\t$root\n"
    )
    val read = Manifest.read(manifest)
    assertEquals(read.map(_.options), Right(Map("core" -> Vector("-Werror", "-deprecation"))))
    assertEquals(read.map(_.sources), Right(Vector(Output("core", Output.Scope.Main, root.resolve("A.scala")))))
    assertEquals(read.map(_.root), Right(Some(root)))
  }

  withRoot("the manifest reads classpath and library lines, and names malformed lines with their position") {
    root =>
      val complete = write(
        root,
        "complete.tsv",
        s"output\tcore\tmain\t${root.resolve("classes")}\n" +
          s"classpath\tcore\t${root.resolve("lib.jar")}\nlibrary\tcore\nroot\t$root\n"
      )
      val read = Manifest.read(complete)
      assertEquals(read.map(_.classpath), Right(Map("core" -> Vector(root.resolve("lib.jar")))))
      assertEquals(read.map(_.libraries), Right(Set("core")))
      assertEquals(read.map(_.root), Right(Some(root)))
      val scoped  = write(root, "scoped.tsv", "output\tcore\tclasses\t/x\n")
      val unknown = write(root, "unknown.tsv", "mystery\tline\n")
      assert(Manifest.read(scoped).left.exists(_.contains("unknown scope: classes")))
      assert(Manifest.read(unknown).left.exists(_.contains("unrecognised manifest line: mystery")))
  }

  withRoot("the jdk line names the target home, and a repeat with the same home is accepted") { root =>
    val home   = root.resolve("jdk-25")
    val once   = write(root, "once.tsv", s"jdk\t$home\nroot\t$root\n")
    val twice  = write(root, "twice.tsv", s"jdk\t$home\njdk\t$home\nroot\t$root\n")
    val absent = write(root, "absent.tsv", s"root\t$root\n")
    assertEquals(Manifest.read(once).map(_.jdk), Right(Some(home)))
    assertEquals(Manifest.read(twice).map(_.jdk), Right(Some(home)))
    assertEquals(Manifest.read(absent).map(_.jdk), Right(None))
  }

  withRoot("a generated line names a directory or a file, whose sources count as generated by either path") { root =>
    val directory = root.resolve("target/src_managed")
    val file      = root.resolve("target/emitted/Gen.scala")
    val manifest  = write(root, "manifest.tsv", s"generated\t$directory\ngenerated\t$file\nroot\t$root\n")
    val read      = Manifest.read(manifest).toOption.get
    assertEquals(read.generated, Vector(directory, file))
    assert(read.isGenerated(Path.of("target/src_managed/main/A.scala")))
    assert(read.isGenerated(directory.resolve("main/A.scala")))
    assert(read.isGenerated(Path.of("target/emitted/Gen.scala")))
    assert(!read.isGenerated(Path.of("target/emitted/Other.scala")))
    assert(!read.isGenerated(Path.of("target/src_managed2/A.scala")))
    assert(!read.isGenerated(Path.of("src/main/scala/A.scala")))
  }

  withRoot("a jdk line naming another home than the first is an error") { root =>
    val manifest = write(root, "manifest.tsv", s"jdk\t${root.resolve("jdk-25")}\njdk\t${root.resolve("jdk-21")}\n")
    assert(Manifest.read(manifest).left.exists(_.contains("conflicting jdk")))
  }

  test("modules without fatal warnings are reported") {
    val manifest = Manifest(
      Vector.empty,
      Map.empty,
      Set.empty,
      options = Map(
        "core"   -> Vector("-Werror"),
        "api"    -> Vector("-deprecation"),
        "legacy" -> Vector("-Xfatal-warnings"),
        "root"   -> Vector("-deprecation"),
        "mixed"  -> Vector("-deprecation", "-Werror")
      ),
      sources = Vector("core", "api", "legacy", "mixed").map(module =>
        Output(module, Output.Scope.Main, Path.of(s"$module.scala"))
      )
    )
    assertEquals(Build.fatal(manifest).map(_.node.name), Vector("api"))
  }

  withRoot("identical sources under the directories of different platforms are reported once per copy set") {
    root =>
      val jvm      = write(root, "api/src/main/scalajvm/Digest.scala", "object Digest")
      val native   = write(root, "api/src/main/scalanative/Digest.scala", "object Digest")
      val js       = write(root, "api/src/main/scalajs/Digest.scala", "object Digest { def js = 1 }")
      val shared   = write(root, "api/src/main/scala/Shared.scala", "object Shared")
      val testJvm  = write(root, "api/src/test/scalajvm/Fixture.scala", "object Fixture")
      val testJs   = write(root, "api/src/test/scalajs/Fixture.scala", "object Fixture")
      val mainCopy = write(root, "api/src/main/scalajvm/Mixed.scala", "object Mixed")
      val testCopy = write(root, "api/src/test/scalajs/Mixed.scala", "object Mixed")
      val manifest = Manifest(
        Vector.empty,
        Map.empty,
        Set.empty,
        sources = Vector(jvm, native, js, shared).flatMap(path =>
          Vector(Output("api", Output.Scope.Main, path), Output("api-native", Output.Scope.Main, path))
        ) ++ Vector(testJvm, testJs, testCopy).map(Output("api", Output.Scope.Test, _)) :+
          Output("api", Output.Scope.Main, mainCopy),
        root = Some(root)
      )
      assertEquals(
        Build.duplicates(manifest).map(finding => (finding.node.name, finding.level)),
        Vector(
          "api/src/main/scalajvm/Digest.scala" -> Finding.Level.Warning,
          "api/src/main/scalajvm/Mixed.scala"  -> Finding.Level.Warning,
          "api/src/test/scalajs/Fixture.scala" -> Finding.Level.Info
        )
      )
  }
}
