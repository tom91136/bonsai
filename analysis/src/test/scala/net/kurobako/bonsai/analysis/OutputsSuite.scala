package net.kurobako.bonsai.analysis

import java.nio.file.Files
import net.kurobako.bonsai.collections.*
import net.kurobako.bonsai.testing.*

class OutputsSuite extends munit.FunSuite {

  test("the files of an output are listed in path order whatever order they were written in") {
    val names = Seq("a/One.tasty", "a/Two.tasty", "b/Three.tasty", "b/c/Four.tasty", "Five.tasty", "z/Six.tasty")
    val roots = Seq(names, names.reverse, names.drop(3) ++ names.take(3)).map { order =>
      val root = Scratch.directory("bonsai-outputs")
      order.foreach { name =>
        val file = root.resolve(name)
        Files.createDirectories(file.getParent)
        Files.writeString(file, "")
      }
      root
    }
    val listings = roots.map(root => Outputs.files(root).map(root.relativize(_).toString))
    assertEquals(listings.map(_.toSet).distinct.size, 1)
    listings.foreach(listing => assertEquals(listing, listing.sorted))
  }

  private val Header = "// Generated by the Scala Plugin for the Protocol Buffer Compiler."

  test("a file marked by the ScalaPB header or an @generated tag in its leading comments is generated") {
    assert(Generated.marked(s"$Header\n// source: point.proto\n\npackage demo\n"))
    assert(Generated.marked("// @generated\npackage demo\n"))
    assert(Generated.marked("\n// the tool\n/* @generated by the tool */\n\npackage demo\n"))
    assert(Generated.marked("/** @generated */\npackage demo;\n"))
  }

  test("a tag or header that is not a leading comment, or not a whole token, leaves a file hand-written") {
    assert(!Generated.marked("package demo\n\n// @generated\n"))
    assert(!Generated.marked(s"package demo\n$Header\n"))
    assert(!Generated.marked("package demo\nval tag = \"@generated\"\n"))
    assert(!Generated.marked("// @generated_by tool\npackage demo\n"))
    assert(!Generated.marked("// @generatedFoo\npackage demo\n"))
    assert(!Generated.marked("// the parser is generated by hand\npackage demo\n"))
    assert(!Generated.marked("// generated by the Scala Plugin for the Protocol Buffer Compiler.\npackage demo\n"))
    assert(!Generated.marked("// Generated by the Scala Plugin for gRPC.\npackage demo\n"))
  }

  test("a file of nothing but comments scans without exhausting the stack") {
    assert(!Generated.marked("// old line\n" * 20000))
  }
}
